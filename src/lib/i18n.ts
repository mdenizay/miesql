const TABLES: Record<string, Partial<Record<MessageKey, string>>> = { en, tr };

/** Resolves "system" against the browser's language list. */
export function resolveLanguage(code: LanguageCode): "en" | "tr" {
  if (code === "en" || code === "tr") return code;
  for (const preferred of navigator.languages ?? [navigator.language]) {
    const base = preferred.split("-")[0];
    if (base === "tr") return "tr";
    if (base === "en") return "en";
  }
  return "en";
}

/**
 * Looks a message up, falling back to English so a partial translation is still usable.
 * Positional arguments fill %1, %2 … which keeps word order free for languages that need
 * a different one.
 */
export function makeTranslator(code: LanguageCode) {
  const table = TABLES[resolveLanguage(code)] ?? en;
  return (key: MessageKey, ...args: (string | number)[]): string => {
    const template = table[key] ?? en[key] ?? key;
    return args.reduce<string>(
      (text, value, index) => text.split(`%${index + 1}`).join(String(value)),
      template,
    );
  };
}

export type Translate = ReturnType<typeof makeTranslator>;
